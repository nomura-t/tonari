async def run(n: int) -> dict:
    sem = asyncio.Semaphore(3)
    rows = []

    async def one(group: str, i: int, said: str, ans: str, k: int) -> None:
        async with sem:
            try:
                alt = await readings.judge(said, ans)
                rows.append({"group": group, "i": i, "run": k, "alt": alt, "error": None})
            except Exception as e:   # 取れなかった回は、札が出ない側に数える（画面でも出ない）
                rows.append({"group": group, "i": i, "run": k, "alt": None, "error": f"{type(e).__name__}: {e}"[:200]})

    await asyncio.gather(*[one(g, i, s, a, k) for g, cases in (("pos", POS), ("neg", NEG))
                           for i, (s, a) in enumerate(cases) for k in range(n)])
    await readings.POOL.close()
    return {"n": n, "rows": sorted(rows, key=lambda r: (r["group"], r["i"], r["run"]))}


def report(d: dict) -> None:
    rows = d["rows"]
    for g, name in (("pos", "別の読みがある組"), ("neg", "別の読みが無い組")):
        rs = [r for r in rows if r["group"] == g]
        hit = sum(bool(r["alt"]) for r in rs)
        print(f"{name}: {len(rs)}回のうち、札が出た {hit}・取れなかった {sum(bool(r['error']) for r in rs)}")
        by = {}
        for r in rs:
            by.setdefault(r["i"], []).append(bool(r["alt"]))
        print("  組ごと（出た回数/流した回数）: " + "・".join(f"{i + 1}:{sum(v)}/{len(v)}" for i, v in sorted(by.items())))
    for r in rows:
        if r["alt"]:
            print(f"  {r['group']}{r['i'] + 1}#{r['run']}: 答えた読み「{r['alt']['took']}」→ " + " / ".join(o["label"] for o in r["alt"]["others"]))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=2)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--report", type=Path)
    a = ap.parse_args()
    if a.report:
        report(json.loads(a.report.read_text(encoding="utf-8")))
        return
    d = asyncio.run(run(a.n))
    if a.out:
        a.out.write_text(json.dumps(d, ensure_ascii=False, indent=1), encoding="utf-8")
    report(d)


if __name__ == "__main__":
    main()
